#!/usr/bin/env node
// Derive domain viewpoints from a database's FK graph.
//
//   node gen-viewpoints.mjs <tbls.json> [--out .tbls.yml] [--dsn-var TBLS_DSN]
//
// Writes:
//   .tbls.yml             tbls config with one viewpoint per derived domain
//   .erd-viewpoints.json  ordered slug list, consumed by build-liam.sh
//
// Domains come from the FK graph, not from table-name guessing:
//   1. A "hub" is any table referenced by >= HUB_MIN others (default 3).
//   2. Hubs claim their direct children in ASCENDING in-degree order, so a
//      specific hub (invoices) claims its children before a mega-hub
//      (orders) can swallow them.
//   3. Each hub's own parents are added as read-only context (overlap is fine).
//   4. Whatever no hub claimed becomes the "reference" domain.

import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const input = args.find((a) => !a.startsWith('--'));
const flag = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? def : args[i + 1];
};

if (!input) {
  console.error('usage: gen-viewpoints.mjs <tbls.json> [--out .tbls.yml] [--dsn-var TBLS_DSN]');
  console.error('  generate the input with: tbls out -t json -o tbls.json "$DSN"');
  process.exit(2);
}

const outPath = flag('out', '.tbls.yml');
const dsnVar = flag('dsn-var', 'TBLS_DSN');
const docPath = flag('doc-path', 'docs/schema');
const HUB_MIN = Number(process.env.ERD_HUB_MIN || flag('hub-min', '3'));

const schema = JSON.parse(fs.readFileSync(input, 'utf8'));
const names = schema.tables.map((t) => t.name);
const relations = schema.relations || [];

const childrenOf = new Map(names.map((n) => [n, []]));
const parentsOf = new Map(names.map((n) => [n, []]));
const inDeg = new Map(names.map((n) => [n, 0]));
const outDeg = new Map(names.map((n) => [n, 0]));

for (const r of relations) {
  // tbls emits snake_case: { table, parent_table }
  const child = r.table;
  const parent = r.parent_table;
  if (!childrenOf.has(parent) || !childrenOf.has(child)) continue;
  childrenOf.get(parent).push(child);
  parentsOf.get(child).push(parent);
  inDeg.set(parent, inDeg.get(parent) + 1);
  outDeg.set(child, outDeg.get(child) + 1);
}

// Hubs, least-referenced first so specific hubs claim before mega-hubs.
const hubs = names
  .filter((n) => inDeg.get(n) >= HUB_MIN)
  .sort((a, b) => inDeg.get(a) - inDeg.get(b));

const slug = (s) => s.replace(/_/g, '-').replace(/[^a-z0-9-]/gi, '').toLowerCase();

const members = new Map(hubs.map((h) => [h, new Set([h])]));
const claimed = new Set(hubs);

for (const h of hubs) {
  for (const c of childrenOf.get(h)) {
    if (claimed.has(c)) continue;
    members.get(h).add(c);
    claimed.add(c);
  }
}
// hub parents as context only — they stay owned by their own domain
for (const h of hubs) for (const p of parentsOf.get(h)) members.get(h).add(p);

const rest = names.filter((n) => !claimed.has(n));
const roots = names.filter((n) => outDeg.get(n) === 0 && inDeg.get(n) > 0);
const orphans = names.filter((n) => inDeg.get(n) === 0 && outDeg.get(n) === 0);

// Biggest domain first — it is the one a reader most needs split further.
const ordered = [...hubs].sort((a, b) => members.get(b).size - members.get(a).size);

const viewpoints = [];
if (hubs.length) {
  viewpoints.push({
    slug: 'context-map',
    name: '00 context-map',
    desc: `Hub and root entities only (${new Set([...hubs, ...roots]).size} tables)`,
    tables: [...new Set([...hubs, ...roots])].sort(),
  });
}
for (const h of ordered) {
  const tables = [...members.get(h)].sort();
  viewpoints.push({
    slug: slug(h),
    name: `${String(viewpoints.length).padStart(2, '0')} ${slug(h)}`,
    desc: `Centered on ${h} (${tables.length} tables)`,
    tables,
  });
}
if (rest.length) {
  viewpoints.push({
    slug: 'reference',
    name: `${String(viewpoints.length).padStart(2, '0')} reference`,
    desc: `Tables no hub claimed — lookups, rates, logs (${rest.length} tables)`,
    tables: [...rest].sort(),
  });
}

const yaml = [
  '# Generated by gen-viewpoints.mjs from the live FK graph. Safe to hand-edit:',
  '# rename viewpoints, split an oversized domain, or reorder. Re-running overwrites.',
  `dsn: \${${dsnVar}}`,
  `docPath: ${docPath}`,
  '',
  'viewpoints:',
];
for (const v of viewpoints) {
  yaml.push(`  - name: ${v.name}`);
  yaml.push(`    desc: ${v.desc}`);
  yaml.push('    tables:');
  for (const t of v.tables) yaml.push(`      - ${t}`);
  yaml.push('');
}

fs.writeFileSync(outPath, yaml.join('\n'));
fs.writeFileSync(
  path.join(path.dirname(outPath), '.erd-viewpoints.json'),
  JSON.stringify({ slugs: viewpoints.map((v) => v.slug) }, null, 2) + '\n',
);

// ---- report ----
console.log(`tables ${names.length} | FK ${relations.length} | hubs ${hubs.length} (in-degree >= ${HUB_MIN})`);
for (const v of viewpoints) console.log(`  ${v.slug.padEnd(28)} ${String(v.tables.length).padStart(3)}`);

const covered = new Set(viewpoints.flatMap((v) => v.tables));
const missing = names.filter((n) => !covered.has(n));
console.log(`coverage ${covered.size}/${names.length}`);
if (missing.length) {
  console.error(`ERROR uncovered tables: ${missing.join(', ')}`);
  process.exit(1);
}
if (!hubs.length) {
  console.log('\nNo hub reached the threshold — this schema is small or flat.');
  console.log('A single diagram is probably more readable than split views.');
}
if (orphans.length) {
  console.log(`\nOrphans (no FK in either direction): ${orphans.join(', ')}`);
  console.log('Often legitimate (logs, rate tables) but worth checking for missing FKs.');
}
console.log(`\nwrote ${outPath} and .erd-viewpoints.json`);
